namespace ProjectR.Activity
{
    /// <summary>
    /// 건물 정의가 활동 하나를 만들어 내는 방법입니다.
    /// </summary>
    /// <remarks>
    /// 건물을 늘리는 것이 활동을 늘리는 것과 같은 일이 되게 하려면(체크리스트 2.6절),
    /// 건물 정의가 "어떤 활동인지"를 들고 있어야 합니다.
    /// 그런데 활동은 만들 때마다 다른 것을 봐야 합니다. 백룸은 가방 스탯을 읽어야 하고,
    /// 미니게임은 남은 횟수를 봐야 합니다. 그래서 활동 자체가 아니라 <b>만드는 방법</b>을 들고 있습니다.
    /// <para>
    /// 정의 에셋에 <c>[SerializeReference]</c>로 담깁니다. 활동을 하나 늘릴 때
    /// 이 인터페이스의 구현을 하나 더 만들고 인스펙터에서 고르면 끝입니다.
    /// <b>건물 종류를 보고 분기하는 <c>if</c>가 생기지 않습니다.</b>
    /// 그런 분기가 생기는 순간이 리스코프 치환을 어긴 지점입니다(체크리스트 1.1절).
    /// </para>
    /// <para>
    /// 활동 어셈블리에 둔 이유는 정의 에셋과 구현체가 둘 다 볼 수 있는 자리이기 때문입니다.
    /// 구현체는 자기 활동이 사는 어셈블리에 둡니다. 백룸 활동을 만드는 구현체는 백룸에 있습니다.
    /// </para>
    /// </remarks>
    public interface IActivityFactory
    {
        #region 프로퍼티
        /// <summary>이 활동에 들어갈 때 드는 방송 시간(분)입니다.</summary>
        /// <remarks>
        /// 건물 정의에 따로 적지 않고 여기서 가져옵니다.
        /// 두 곳에 적으면 활동의 비용을 바꿨을 때 건물에 적힌 안내가 조용히 어긋납니다.
        /// </remarks>
        int BroadcastCost { get; }
        #endregion // 프로퍼티

        #region 함수
        /// <summary>
        /// 지금 상태에 맞는 활동을 만듭니다.
        /// </summary>
        /// <returns>만들어진 활동입니다.</returns>
        IActivity Create();
        #endregion // 함수
    }
}
